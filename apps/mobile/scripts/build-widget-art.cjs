// Recompose the existing HomeScreen SVG layers, without introducing new artwork.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const component = fs
  .readFileSync(
    path.join(root, "src/features/notices/components/LetterIllustration.tsx"),
    "utf8",
  )
  .split("export function LetterIllustration")[1];
const images = [
  ...component.matchAll(
    /<Image\s+source=\{require\("@\/assets\/figma\/([^\"]+)"\)\}\s+style=\{\{([\s\S]*?)\}\}\s*\/>/g,
  ),
];
const layers = images
  .filter(([, , style]) => style.includes('position: "absolute"'))
  .map(([_, file, style], index) => {
    const number = (key) =>
      Number(style.match(new RegExp(`${key}: ([\\d.]+)`))[1]);
    const [x, y, w, h] = ["left", "top", "width", "height"].map(number);
    const rotate = Number(style.match(/rotate: "([\d.]+)deg"/)?.[1] ?? 0);
    let svg = fs.readFileSync(path.join(root, "assets/figma", file), "utf8");
    // SVG ids are local to each Figma export; make them unique in the composition.
    svg = svg
      .replace(/id="([^"]+)"/g, `id="layer${index}-$1"`)
      .replace(/url\(#([^)]+)\)/g, `url(#layer${index}-$1)`);
    svg = svg
      .replace("<svg ", `<svg x="${x}" y="${y}" `)
      .replace(/width="[^"]+"/, `width="${w}"`)
      .replace(/height="[^"]+"/, `height="${h}"`);
    return `<g transform="rotate(${rotate} ${x + w / 2} ${y + h / 2})">${svg}</g>`;
  });
if (layers.length !== 15)
  throw new Error(
    `Review HomeScreen art changes: expected 15 layers, got ${layers.length}`,
  );
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="314" height="473" viewBox="0 0 314 473">${layers.join("")}</svg>`;
fs.writeFileSync(
  path.join(root, "src/features/widget/letterArtwork.ts"),
  `// Generated by scripts/build-widget-art.cjs from LetterIllustration.tsx.\nexport const LETTER_ARTWORK = ${JSON.stringify(svg)};\n`,
);
fs.mkdirSync(path.join(root, "assets/widget"), { recursive: true });
fs.writeFileSync(path.join(root, "assets/widget/letter.svg"), svg);
